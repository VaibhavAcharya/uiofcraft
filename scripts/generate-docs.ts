import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { toPhosphor } from "./phosphor-icons.ts";

const root = join(import.meta.dirname, "..");
const docsDir = join(root, "docs", "components");
const cossDocs =
  "https://raw.githubusercontent.com/cosscom/ui/main/apps/ui/content/docs/components";
const cossDocsList =
  "https://api.github.com/repos/cosscom/ui/contents/apps/ui/content/docs/components";

const droppedSections = new Set(["Installation", "Examples", "Changelog"]);

const handWritten: Record<
  string,
  { description: string; exampleFile: string }
> = {
  sidebar: {
    description:
      "An app sidebar with a header, groups, menus, a footer and a trigger that collapses it.",
    exampleFile: "stories/sidebar-example.tsx",
  },
};

const titleCase = (slug: string) =>
  slug
    .split("-")
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join(" ");

const toPackageImports = (text: string) =>
  text
    .replace(
      /from ["']@\/(registry\/default\/ui|components\/ui)\/[a-z-]+["']/g,
      'from "uiofcraft"',
    )
    .replace(/from ["']@\/(lib|hooks)\/[a-z-]+["']/g, 'from "uiofcraft"');

const rebrand = (text: string) =>
  text
    .replace(" Add `@coss/table` if it is not already in the project.", "")
    .replaceAll("application/x-coss-composer", "\0composer-mime\0")
    .replaceAll("**coss ui**", "**uiofcraft**")
    .replaceAll("coss ui", "uiofcraft")
    .replace(/\bcoss\b/g, "uiofcraft")
    .replaceAll("\0composer-mime\0", "application/x-coss-composer");

const localLinks = (text: string) =>
  text.replace(
    /\]\((?:\/ui)?\/docs\/components\/([a-z-]+)\)/g,
    (_, name) => `](./${name}.md)`,
  );

function exampleCode(particle: string) {
  const [, group, number] = particle.match(/^p-(.+)-(\d+)$/) ?? [];
  const component = group === "navigation" ? "segmented-control" : group;
  const file = join(
    root,
    "stories",
    "examples",
    component,
    `${group}-${number}.tsx`,
  );
  if (!existsSync(file)) {
    throw new Error(`No example file for ${particle}`);
  }
  return readFileSync(file, "utf8").replace(/^"use client";\n\n/, "");
}

function cleanBody(body: string) {
  const lines: string[] = [];
  let inCode = false;
  for (const line of body.split("\n")) {
    if (line.startsWith("```")) inCode = !inCode;
    if (inCode) {
      lines.push(line);
      continue;
    }
    const preview = line.match(/^<ComponentPreview name="([^"]+)"/);
    if (preview) {
      lines.push("```tsx", exampleCode(preview[1]).trimEnd(), "```");
      continue;
    }
    if (/^\s*<\/?[A-Za-z][^>]*>\s*$/.test(line)) continue;
    lines.push(line);
  }
  return lines.join("\n");
}

function sections(mdx: string) {
  const body = mdx.replace(/^---\n[\s\S]*?\n---\n/, "");
  const kept: string[] = [];
  let keep = false;
  for (const line of body.split("\n")) {
    const heading = line.match(/^## (.+)$/);
    if (heading) keep = !droppedSections.has(heading[1].trim());
    if (keep) kept.push(line);
  }
  return kept.join("\n").trim();
}

async function fetchText(url: string) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${response.status} ${url}`);
  return response.text();
}

async function exportsOf(component: string) {
  const file = join(root, "dist", "components", "ui", `${component}.js`);
  if (!existsSync(file)) return [];
  const module = await import(file);
  return Object.keys(module).sort();
}

const componentFiles = new Set(
  readdirSync(join(root, "src", "components", "ui")).map((file) =>
    file.replace(/\.tsx$/, ""),
  ),
);

const listing = JSON.parse(await fetchText(cossDocsList)) as { name: string }[];
const documented = listing
  .map((entry) => entry.name)
  .filter((name) => name.endsWith(".mdx"))
  .map((name) => name.replace(/\.mdx$/, ""));

type Page = {
  name: string;
  title: string;
  description: string;
  isComponent: boolean;
};
const pages: Page[] = [];

rmSync(docsDir, { recursive: true, force: true });
mkdirSync(docsDir, { recursive: true });

const generatedNote =
  "<!-- Generated by scripts/generate-docs.ts from the coss ui docs. Do not edit by hand. -->";

for (const name of documented) {
  const mdx = await fetchText(`${cossDocs}/${name}.mdx`);
  const frontmatter = mdx.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? "";
  const title =
    frontmatter.match(/^title:\s*(.+)$/m)?.[1].trim() ?? titleCase(name);
  const description = rebrand(
    frontmatter.match(/^description:\s*(.+)$/m)?.[1].trim() ?? "",
  );
  const isComponent = componentFiles.has(name);
  const exports = isComponent ? await exportsOf(name) : [];
  const body = toPhosphor(
    toPackageImports(localLinks(rebrand(cleanBody(sections(mdx))))),
    name,
  );

  const exportsLine = exports.length
    ? `Exports from \`uiofcraft\` and \`uiofcraft/${name}\`: ${exports.map((e) => `\`${e}\``).join(", ")}.\n\n`
    : "";
  writeFileSync(
    join(docsDir, `${name}.md`),
    `${generatedNote}\n\n# ${title}\n\n${description}\n\n${exportsLine}${body}\n`,
  );
  pages.push({ name, title, description, isComponent });
}

for (const [name, page] of Object.entries(handWritten)) {
  const exports = await exportsOf(name);
  const code = toPhosphor(
    toPackageImports(readFileSync(join(root, page.exampleFile), "utf8")),
    name,
  );
  writeFileSync(
    join(docsDir, `${name}.md`),
    `${generatedNote}\n\n# ${titleCase(name)}\n\n${page.description}\n\nExports from \`uiofcraft\` and \`uiofcraft/${name}\`: ${exports.map((e) => `\`${e}\``).join(", ")}.\n\n## Usage\n\n\`\`\`tsx\n${code.trimEnd()}\n\`\`\`\n`,
  );
  pages.push({
    name,
    title: titleCase(name),
    description: page.description,
    isComponent: true,
  });
}

const missing = [...componentFiles].filter(
  (name) => !pages.some((page) => page.name === name),
);
if (missing.length > 0) {
  throw new Error(`No docs for ${missing.join(", ")}`);
}

pages.sort((a, b) => a.name.localeCompare(b.name));
const row = (page: Page) =>
  `| [${page.title}](./${page.name}.md) | ${page.description} |`;

writeFileSync(
  join(docsDir, "README.md"),
  `${generatedNote}

# Components

Import every component from \`uiofcraft\`, or from \`uiofcraft/<name>\` for one file. Read [../usage.md](../usage.md) first.

| Component | What it is |
|---|---|
${pages
  .filter((page) => page.isComponent)
  .map(row)
  .join("\n")}

## Patterns

Built from the components above, not exported on their own.

| Pattern | What it is |
|---|---|
${pages
  .filter((page) => !page.isComponent)
  .map(row)
  .join("\n")}
`,
);

console.log(`Wrote ${pages.length} pages to docs/components`);
